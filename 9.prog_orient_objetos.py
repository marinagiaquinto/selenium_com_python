# Classe:
# É uma abstração que representa algo do mundo real. 
# É um molde, que agrupa características comuns (atributos) em todos os elementos. 
# ex: classe -> pássaros (todos tem asas, bicos, patas, ...)
# São características que os fazem ser definidos como participante de um grupo em específico (a classe).

# Atributos
# Descrevem o estado de um objeto (uma instância da classe)
# São compartilhados entre os elementos da classe. Não por ter o mesmo valor, mas 
# por todos os objetos da classe terem os mesmos atributos.
# ex: cor, tipo de pena, tipo de bico, ...

# Métodos
# Funções internas a classe. Abstrações de processos executados pela classe.
# Ações.
# ex: pássaros voam, cantam, comem.

# Objeto ou Instância
# É a representação concreta de uma classe.
# É um grupo específico que contém características em comum dentro da classe. 
# É a coisa em si e não mais a abstração da coisa (que seria a classe).
# ex: pardal, bentevi, beija-flor, ...


# Padrão de projeto
# Padrão de projeto é um guia de como seguir estruturalmente no projeto para atender 
# nossas necessidades. Como um guia, possui fundamentos base que todos devem ter, 
# mas também existem diferenças entre eles conforme as demais necessidades. 

# Padrões de projeto são soluções típicas para problemas comuns no desing de software.
# São modelos pré-fabricados que você pode personalizar para resolver um problema de desing 
# recorrente no seu código.